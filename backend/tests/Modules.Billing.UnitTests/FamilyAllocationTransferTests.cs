/// <summary>
/// Test-only <see cref="BillingDbContext"/> subclass that overrides the <c>xmin</c>
/// row-version mapping for <see cref="ChildEnergyAllocation"/> and <see cref="FamilyEnergyAccount"/>
/// so that EF can INSERT those rows in SQLite without failing on NOT NULL.
///
/// On Postgres, <c>xmin</c> is a system column generated by the DB on every write.
/// On SQLite (tests only), there is no such system column, so we must supply a default value.
/// This override applies <c>HasDefaultValue(1u)</c> for the SQLite schema only.
/// It has NO effect on the real Postgres schema or migrations.
/// </summary>
internal sealed class BillingTestDbContext : BillingDbContext
{
    public BillingTestDbContext(DbContextOptions<BillingDbContext> options) : base(options) { }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);

        // SQLite-only: supply a default of 1 for the xmin columns so EF INSERT works.
        // The column is normally generated by Postgres (server-side xmin); EF omits it from INSERTs.
        // SQLite has no such generator → NOT NULL fails unless a default is available.
        modelBuilder.Entity<ChildEnergyAllocation>()
            .Property(x => x.Version)
            .HasDefaultValue(1u);

        modelBuilder.Entity<FamilyEnergyAccount>()
            .Property(x => x.Version)
            .HasDefaultValue(1u);
    }
}

/// <summary>
/// Focused unit tests for P10-16 family allocation redistribution correctness.
///
/// All services run against SQLite in-memory (no Postgres required).
/// The real <see cref="BillingDbContext"/> is used with SQLite.
///
/// Note on seeding: <see cref="FamilyEnergyAccount"/> and <see cref="ChildEnergyAllocation"/>
/// both carry a <c>uint Version</c> mapped to the Postgres <c>xmin</c> system column as a
/// row-version concurrency token. SQLite does NOT auto-generate this column, so these two
/// entity types must be seeded via raw SQL (explicit <c>xmin=1</c>).
/// <see cref="Subscription"/> and <see cref="SeatReservation"/> have no <c>Version</c> column
/// and use standard EF Add + SaveChangesAsync.
///
/// Coverage:
///   AT-01  Cross-family rejection: fromChildId does not belong to this parent's wallet → Fail(ChildNotInFamily).
///   AT-02  Cross-family rejection: toChildId does not belong to this parent's wallet → Fail(ChildNotInFamily).
///   AT-03  Amount > source.Remaining → Fail(AmountExceedsRemaining).
///   AT-04  Amount = 0 → Fail(AmountExceedsRemaining).
///   AT-05  Only UNSPENT is movable: Allocated=100, Spent=60, Remaining=40;
///          transfer 41 → Fail; transfer 40 → Ok.
///   AT-06  Mid-cycle child with no allocation row: transfer to them
///          INSERTs a new ChildEnergyAllocation row and succeeds.
///   AT-07  Paired ledger rows: TransferOut (source) + TransferIn (destination)
///          share the same CorrelationId; both touch bucket A (Subscription) only.
///   AT-08  Idempotency: same IdempotencyKey twice does NOT double-move;
///          second call returns the prior result without appending new ledger rows.
///   AT-09  GetFamilyAllocationAsync: IsMidCycleNoGrant=true for a child with an active
///          seat but no current-cycle allocation row.
///   AT-10  GetFamilyAllocationAsync: all active-seat children appear, including zero-allocation ones.
/// </summary>
public sealed class FamilyAllocationTransferTests : IDisposable
{
    // ── SQLite fixtures ───────────────────────────────────────────────────────────────────────

    private readonly SqliteConnection _connection;
    private readonly BillingTestDbContext _db;
    private readonly Mock<ISeatStateQuery> _seatStateQueryMock;
    private readonly Mock<ICurrentUserService> _currentUserMock;

    public FamilyAllocationTransferTests()
    {
        _connection = new SqliteConnection("DataSource=:memory:");
        _connection.Open();

        var options = new DbContextOptionsBuilder<BillingDbContext>()
            .UseSqlite(_connection)
            .Options;

        _db = new BillingTestDbContext(options);
        _db.Database.EnsureCreated();

        _seatStateQueryMock = new Mock<ISeatStateQuery>();
        _currentUserMock    = new Mock<ICurrentUserService>();
        _currentUserMock.Setup(x => x.UserId).Returns(1);
    }

    public void Dispose()
    {
        _db.Dispose();
        _connection.Dispose();
    }

    private FamilyAllocationService BuildService()
    {
        var loggerMock = new Mock<ILoggerManager>();
        loggerMock.Setup(x => x.LogInfo(It.IsAny<string>()));
        loggerMock.Setup(x => x.LogError(It.IsAny<Exception>(), It.IsAny<string>()));
        return new FamilyAllocationService(_db, _seatStateQueryMock.Object, _currentUserMock.Object, loggerMock.Object);
    }

    // ── Seed helpers ──────────────────────────────────────────────────────────────────────────

    /// <summary>
    /// Seeds a Subscription row using standard EF (no xmin column).
    /// Returns the created entity (with its generated Id).
    /// </summary>
    private async Task<Subscription> SeedSubscriptionAsync(int parentId = 1)
    {
        var sub = new Subscription
        {
            ParentUserId  = parentId,
            PlanCode      = PlanCode.Premium,
            Status        = SubscriptionStatus.Active,
            BillingPeriod = BillingPeriod.Monthly,
            CreatedAt     = DateTime.UtcNow.AddMonths(-1),
            CreatedBy     = 0,
        };
        _db.Subscriptions.Add(sub);
        await _db.SaveChangesAsync();
        return sub;
    }

    /// <summary>
    /// Seeds a FamilyEnergyAccount via raw SQL because the entity has uint Version mapped
    /// to the Postgres xmin system column — SQLite won't auto-generate it.
    /// Returns the generated Id.
    /// </summary>
    private async Task<int> SeedWalletAsync(int parentId = 1)
    {
        var now = DateTime.UtcNow.ToString("o");
        await _db.Database.ExecuteSqlRawAsync(
            $"""
            INSERT INTO "FamilyEnergyAccounts"
                ("ParentUserId","SubscriptionBalance","PurchasedBalance","xmin","CreatedAt","CreatedBy")
            VALUES
                ({parentId},0,0,1,'{now}',0)
            """);

        return await _db.FamilyEnergyAccounts
            .AsNoTracking()
            .Where(w => w.ParentUserId == parentId)
            .Select(w => w.Id)
            .FirstAsync();
    }

    /// <summary>
    /// Seeds a SeatReservation using standard EF (no xmin column).
    /// </summary>
    private async Task SeedActiveSeatAsync(int subscriptionId, int childId, int parentId = 1, SeatState seatState = SeatState.Active)
    {
        var reservation = new SeatReservation
        {
            SubscriptionId = subscriptionId,
            ChildId        = childId,
            ParentUserId   = parentId,
            Status         = SeatStatus.Active,
            SeatState      = seatState,
            ReservedAt     = DateTime.UtcNow,
            CreatedAt      = DateTime.UtcNow,
            CreatedBy      = 0,
        };
        _db.SeatReservations.Add(reservation);
        await _db.SaveChangesAsync();
    }

    /// <summary>
    /// Seeds a ChildEnergyAllocation via raw SQL because the entity has uint Version mapped
    /// to the Postgres xmin system column — SQLite won't auto-generate it.
    /// </summary>
    private async Task SeedAllocationAsync(int walletId, int childId, int allocated, int spent)
    {
        var now        = DateTime.UtcNow.ToString("o");
        var cycleStart = DateTime.UtcNow.AddDays(-15).ToString("o");
        var cycleEnd   = DateTime.UtcNow.AddDays(15).ToString("o");
        await _db.Database.ExecuteSqlRawAsync(
            $"""
            INSERT INTO "ChildEnergyAllocations"
                ("FamilyEnergyAccountId","ChildId","CycleStartUtc","CycleEndUtc",
                 "AllocatedAmount","SpentAmount","xmin","CreatedAt","CreatedBy")
            VALUES
                ({walletId},{childId},'{cycleStart}','{cycleEnd}',
                 {allocated},{spent},1,'{now}',0)
            """);
    }

    /// <summary>
    /// Resolves the ChildEnergyAllocation Id for a given child in a wallet (needed for ledger assertions).
    /// </summary>
    private async Task<int> GetAllocationIdAsync(int walletId, int childId)
        => await _db.ChildEnergyAllocations
            .AsNoTracking()
            .Where(a => a.FamilyEnergyAccountId == walletId && a.ChildId == childId)
            .Select(a => a.Id)
            .FirstAsync();

    // ── AT-01: fromChildId not in family ─────────────────────────────────────────────────────

    [Fact]
    public async Task AT01_FromChildId_NotInFamily_Returns_ChildNotInFamily()
    {
        var sub      = await SeedSubscriptionAsync(parentId: 1);
        var walletId = await SeedWalletAsync(parentId: 1);
        await SeedActiveSeatAsync(sub.Id, childId: 10);
        await SeedAllocationAsync(walletId, childId: 10, allocated: 200, spent: 0);

        // fromChildId=99 has NO active seat in this family.
        _seatStateQueryMock.Setup(x => x.IsChildSeatActiveAsync(It.IsAny<int>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        var svc    = BuildService();
        var result = await svc.TransferAllocationAsync(1, fromChildId: 99, toChildId: 10, 50, "key-001");

        result.Succeeded.Should().BeFalse();
        result.FailureReason.Should().Be(TransferAllocationFailureReason.ChildNotInFamily);
    }

    // ── AT-02: toChildId not in family ───────────────────────────────────────────────────────

