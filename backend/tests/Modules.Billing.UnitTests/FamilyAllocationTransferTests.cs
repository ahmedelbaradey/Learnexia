    // ── AT-05: only UNSPENT is movable ────────────────────────────────────────────────────────

    [Fact]
    public async Task AT05_OnlyUnspentMovable_Transfer41_Fails_Transfer40_Succeeds()
    {
        var sub      = await SeedSubscriptionAsync(parentId: 1);
        var walletId = await SeedWalletAsync(parentId: 1);
        await SeedActiveSeatAsync(sub.Id, childId: 10);
        await SeedActiveSeatAsync(sub.Id, childId: 20);
        // Allocated=100, Spent=60 → Remaining=40
        await SeedAllocationAsync(walletId, childId: 10, allocated: 100, spent: 60);
        await SeedAllocationAsync(walletId, childId: 20, allocated: 50, spent: 0);

        _seatStateQueryMock.Setup(x => x.IsChildSeatActiveAsync(It.IsAny<int>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        var svc = BuildService();

        // Transfer 41 → fails (exceeds Remaining=40).
        var fail = await svc.TransferAllocationAsync(1, fromChildId: 10, toChildId: 20, 41, "key-005a");
        fail.Succeeded.Should().BeFalse();
        fail.FailureReason.Should().Be(TransferAllocationFailureReason.AmountExceedsRemaining);

        // Transfer 40 → succeeds.
        var ok = await svc.TransferAllocationAsync(1, fromChildId: 10, toChildId: 20, 40, "key-005b");
        ok.Succeeded.Should().BeTrue();
        ok.Data.Should().NotBeNull();

        // source: Allocated=100, Spent was 60, SendTransfer adds 40 → SpentAmount=100 → Remaining=0.
        ok.Data!.FromChild.Remaining.Should().Be(0);
        // dest: Allocated was 50, ReceiveTransfer adds 40 → AllocatedAmount=90 → Remaining=90.
        ok.Data.ToChild.Remaining.Should().Be(90);
    }

    // ── AT-06: mid-cycle child INSERT-then-transfer ───────────────────────────────────────────

    [Fact]
    public async Task AT06_MidCycle_DestHasNoAllocationRow_InsertsRow_AndTransferSucceeds()
    {
        var sub      = await SeedSubscriptionAsync(parentId: 1);
        var walletId = await SeedWalletAsync(parentId: 1);
        await SeedActiveSeatAsync(sub.Id, childId: 10);
        await SeedActiveSeatAsync(sub.Id, childId: 20); // mid-cycle child — no alloc row
        await SeedAllocationAsync(walletId, childId: 10, allocated: 200, spent: 0);
        // childId=20 has NO ChildEnergyAllocation row.

        _seatStateQueryMock.Setup(x => x.IsChildSeatActiveAsync(It.IsAny<int>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        var svc    = BuildService();
        var result = await svc.TransferAllocationAsync(1, fromChildId: 10, toChildId: 20, 50, "key-006");

        result.Succeeded.Should().BeTrue("mid-cycle child with active seat is a valid destination");
        result.Data.Should().NotBeNull();
        result.Data!.ToChild.ChildId.Should().Be(20);
        result.Data.ToChild.Remaining.Should().Be(50);

        // Verify the INSERT happened.
        var destRow = await _db.ChildEnergyAllocations
            .AsNoTracking()
            .Where(a => a.FamilyEnergyAccountId == walletId && a.ChildId == 20)
            .FirstOrDefaultAsync();
        destRow.Should().NotBeNull("a ChildEnergyAllocation row must be created for the mid-cycle destination child");
        // After ReceiveTransfer: AllocatedAmount = 0+50 = 50; SpentAmount = 0; Remaining = 50.
        destRow!.AllocatedAmount.Should().Be(50);
        destRow.SpentAmount.Should().Be(0);
    }

    // ── AT-07: paired ledger rows with shared CorrelationId ──────────────────────────────────

    [Fact]
    public async Task AT07_PairedLedgerRows_ShareCorrelationId()
    {
        var sub      = await SeedSubscriptionAsync(parentId: 1);
        var walletId = await SeedWalletAsync(parentId: 1);
        await SeedActiveSeatAsync(sub.Id, childId: 10);
        await SeedActiveSeatAsync(sub.Id, childId: 20);
        await SeedAllocationAsync(walletId, childId: 10, allocated: 200, spent: 0);
        await SeedAllocationAsync(walletId, childId: 20, allocated: 100, spent: 0);

        var srcAllocId  = await GetAllocationIdAsync(walletId, 10);
        var destAllocId = await GetAllocationIdAsync(walletId, 20);

        _seatStateQueryMock.Setup(x => x.IsChildSeatActiveAsync(It.IsAny<int>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        var svc    = BuildService();
        var result = await svc.TransferAllocationAsync(1, fromChildId: 10, toChildId: 20, 75, "key-007");

        result.Succeeded.Should().BeTrue();

        var txOut = await _db.CreditTransactions
            .AsNoTracking()
            .Where(t => t.ChildEnergyAllocationId == srcAllocId
                     && t.ReasonCode == CreditReasonCode.TransferOut)
            .FirstOrDefaultAsync();

        var txIn = await _db.CreditTransactions
            .AsNoTracking()
            .Where(t => t.ChildEnergyAllocationId == destAllocId
                     && t.ReasonCode == CreditReasonCode.TransferIn)
            .FirstOrDefaultAsync();

        txOut.Should().NotBeNull("TransferOut ledger row must be appended for source child");
        txIn.Should().NotBeNull("TransferIn ledger row must be appended for destination child");

        txOut!.Amount.Should().Be(75);
        txIn!.Amount.Should().Be(75);

        txOut.CorrelationId.Should().NotBeNull("TransferOut must carry a CorrelationId");
        txIn.CorrelationId.Should().NotBeNull("TransferIn must carry a CorrelationId");
        txOut.CorrelationId.Should().Be(txIn.CorrelationId,
            "the paired ledger rows must share the same CorrelationId");

        txOut.SourceBucket.Should().Be(EnergyBucket.Subscription,
            "transfers touch bucket A (Subscription) only — never bucket B (Purchased)");
        txIn.SourceBucket.Should().Be(EnergyBucket.Subscription);
    }

    // ── AT-08: idempotency — same key does NOT double-move ───────────────────────────────────

    [Fact]
    public async Task AT08_Idempotency_SameKey_DoesNotDoubleMove()
    {
        var sub      = await SeedSubscriptionAsync(parentId: 1);
        var walletId = await SeedWalletAsync(parentId: 1);
        await SeedActiveSeatAsync(sub.Id, childId: 10);
        await SeedActiveSeatAsync(sub.Id, childId: 20);
        await SeedAllocationAsync(walletId, childId: 10, allocated: 200, spent: 0);
        await SeedAllocationAsync(walletId, childId: 20, allocated: 0, spent: 0);

        _seatStateQueryMock.Setup(x => x.IsChildSeatActiveAsync(It.IsAny<int>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        var svc = BuildService();

        // First call.
        var first = await svc.TransferAllocationAsync(1, 10, 20, 50, "key-008-idempotent");
        first.Succeeded.Should().BeTrue();

        // Second call with the same key.
        var second = await svc.TransferAllocationAsync(1, 10, 20, 50, "key-008-idempotent");
        second.Succeeded.Should().BeTrue("re-submit must return prior result without double-move");

        // Only ONE TransferOut row must exist (idempotency enforced on IdempotencyKey unique index).
        var outCount = await _db.CreditTransactions
            .AsNoTracking()
            .CountAsync(t => t.ReasonCode == CreditReasonCode.TransferOut
                          && t.IdempotencyKey == "transfer-out:key-008-idempotent");
        outCount.Should().Be(1, "idempotent replay must NOT append a second TransferOut row");

        // Source remaining must reflect exactly ONE transfer of 50, not two.
        var srcAlloc = await _db.ChildEnergyAllocations
            .AsNoTracking()
            .Where(a => a.FamilyEnergyAccountId == walletId && a.ChildId == 10)
            .FirstOrDefaultAsync();
        srcAlloc!.Remaining.Should().Be(150, "only 50 should have been moved, not 100");
    }

    // ── AT-09: GetFamilyAllocationAsync — IsMidCycleNoGrant=true for child with no alloc row ─

    [Fact]
    public async Task AT09_GetAllocation_MidCycleChild_HasIsMidCycleNoGrant_True()
    {
        var sub      = await SeedSubscriptionAsync(parentId: 1);
        var walletId = await SeedWalletAsync(parentId: 1);
        await SeedActiveSeatAsync(sub.Id, childId: 10);
        await SeedActiveSeatAsync(sub.Id, childId: 20); // mid-cycle child — no alloc row
        await SeedAllocationAsync(walletId, childId: 10, allocated: 300, spent: 50);
        // childId=20 has NO allocation row.

        _seatStateQueryMock.Setup(x => x.IsChildSeatActiveAsync(It.IsAny<int>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        var svc = BuildService();
        var dto = await svc.GetFamilyAllocationAsync(1);

        dto.Should().NotBeNull();
        dto!.Children.Should().HaveCount(2, "both active-seat children must appear");

        var child10 = dto.Children.Single(c => c.ChildId == 10);
        child10.IsMidCycleNoGrant.Should().BeFalse();
        child10.Remaining.Should().Be(250);

        var child20 = dto.Children.Single(c => c.ChildId == 20);
        child20.IsMidCycleNoGrant.Should().BeTrue("mid-cycle child with no allocation row must be flagged");
        child20.Allocated.Should().Be(0);
        child20.Spent.Should().Be(0);
        child20.Remaining.Should().Be(0);
    }

    // ── AT-10: GetFamilyAllocationAsync returns ALL active-seat children ──────────────────────

    [Fact]
    public async Task AT10_GetAllocation_ReturnsAll_ActiveSeatChildren_Including_ZeroAllocation()
    {
        var sub      = await SeedSubscriptionAsync(parentId: 1);
        var walletId = await SeedWalletAsync(parentId: 1);
        await SeedActiveSeatAsync(sub.Id, childId: 10);
        await SeedActiveSeatAsync(sub.Id, childId: 20);
        await SeedActiveSeatAsync(sub.Id, childId: 30);
        // Only childId=10 has an allocation row.
        await SeedAllocationAsync(walletId, childId: 10, allocated: 500, spent: 100);

        _seatStateQueryMock.Setup(x => x.IsChildSeatActiveAsync(It.IsAny<int>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        var svc = BuildService();
        var dto = await svc.GetFamilyAllocationAsync(1);

        dto.Should().NotBeNull();
        dto!.Children.Should().HaveCount(3, "all three active-seat children must appear");

        dto.Children.Where(c => !c.IsMidCycleNoGrant).Should().HaveCount(1,
            "only child 10 has a grant row");
        dto.Children.Where(c => c.IsMidCycleNoGrant).Should().HaveCount(2,
            "children 20 and 30 have no allocation row → IsMidCycleNoGrant=true");
    }
