        var result = await svc.TransferAllocationAsync(1, fromChildId: 10, toChildId: 20, 101, "key-003");

        result.Succeeded.Should().BeFalse();
        result.FailureReason.Should().Be(TransferAllocationFailureReason.AmountExceedsRemaining);
