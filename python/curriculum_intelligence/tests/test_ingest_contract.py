"""BL-05-PY-5-contract — Testcontainers Postgres proof of the INGEST claim/advance
contract (mirrors ``tests/test_outbox_contract.py`` for the ingest lane).

Proves, against a real Postgres mirroring the shipped EF schema:
  1. The ingest poller claims ONLY ``JobType='ingest'`` rows (a Pending parse job
     is left untouched — lane isolation).
  2. The claim is atomic (Pending -> Processing) and concurrency-safe.
  3. The Done write-back carries the ``{nodes, chunks, flags}`` ResultJson the
     .NET IngestJobAdvanceService reads, with Status + CompletedAt set.
  4. A Failed ingest job writes the diagnostics shape the .NET side reads, and the
     worker does NOT touch RetryCount (that is .NET's policy).

Skipped automatically when Docker is unavailable (sandboxed runner).
"""

